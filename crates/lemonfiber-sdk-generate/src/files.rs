use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::Refused;

pub fn json(path: &Path, shown: &str) -> Result<Value, Refused> {
    let text = text(path, shown)?;
    serde_json::from_str(&text)
        .map_err(|error| Refused::new(format!("{shown} is not JSON: {error}")))
}

pub fn text(path: &Path, shown: &str) -> Result<String, Refused> {
    fs::read_to_string(path)
        .map_err(|error| Refused::new(format!("{shown} could not be read: {error}")))
}

pub fn beneath(directory: &Path) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    gather(directory, "", &mut found);
    found
}

fn gather(directory: &Path, prefix: &str, found: &mut BTreeSet<String>) {
    for entry in fs::read_dir(directory).into_iter().flatten().flatten() {
        let named = format!("{prefix}{}", entry.file_name().to_string_lossy());
        if entry.path().is_dir() {
            gather(&entry.path(), &format!("{named}/"), found);
        } else {
            found.insert(named);
        }
    }
}

pub fn written(done: std::io::Result<()>, path: &Path) -> Result<(), Refused> {
    done.map_err(|error| Refused::new(format!("{} could not be written: {error}", path.display())))
}

pub fn write(directory: &Path, files: &[(String, String)]) -> Result<(), Refused> {
    let keeping: BTreeSet<&str> = files.iter().map(|(path, _)| path.as_str()).collect();
    for stale in beneath(directory) {
        if !keeping.contains(stale.as_str()) {
            let path = directory.join(&stale);
            written(fs::remove_file(&path), &path)?;
        }
    }
    for (path, content) in files {
        let path: PathBuf = directory.join(path);
        let parent = path.parent().unwrap_or(directory);
        written(fs::create_dir_all(parent), parent)?;
        written(fs::write(&path, content), &path)?;
    }
    Ok(())
}

pub fn compare(directory: &Path, written: &[(String, String)]) -> Result<(), Refused> {
    let mut problems = Vec::new();
    let held = beneath(directory);
    for (path, content) in written {
        if !held.contains(path) {
            problems.push(format!("{path} is not committed"));
        } else if fs::read_to_string(directory.join(path)).ok().as_deref() != Some(content) {
            problems.push(format!("{path} differs from what the contract generates"));
        }
    }
    let writing: BTreeSet<&str> = written.iter().map(|(path, _)| path.as_str()).collect();
    problems.extend(
        held.iter()
            .filter(|path| !writing.contains(path.as_str()))
            .map(|path| format!("{path} is generated by nothing")),
    );
    if problems.is_empty() {
        Ok(())
    } else {
        Err(Refused::listing(
            "the generated module is not what the vendored contract generates; run `just generate` and commit it",
            &problems,
        ))
    }
}
